#!/usr/bin/env bash
# Reproducible PhotoSweep benchmark. Usage: scripts/benchmark.sh [file-count] [memory-scale counts...]
#   scripts/benchmark.sh 2000 500 2000 8000
# Generates synthetic photo-sized JPEGs under bench-data/ (git-ignored), runs release builds,
# and prints a Markdown report. Each timing is the median of $RUNS runs.
set -euo pipefail
cd "$(dirname "$0")/.."

COUNT=${1:-2000}
shift || true
MEMORY_COUNTS=("${@:-500 2000}")
RUNS=${RUNS:-3}
DATA=bench-data
OUT=$DATA/results
mkdir -p "$OUT"

swift build -c release -q
PS=.build/release/photosweep
DEV=.build/release/photosweep-dev

# run <label> <args...>: runs a scan under /usr/bin/time, records "seconds rss_bytes summary"
run() {
  local log=$OUT/run.log
  /usr/bin/time -l "$PS" scan "$@" >"$log.stdout" 2>"$log.time"
  local secs rss
  secs=$(grep -Eo 'in [0-9.]+s' "$log.stdout" | head -1 | tr -dc '0-9.')
  rss=$(awk '/maximum resident set size/ {print $1}' "$log.time")
  echo "$secs $rss"
}

median() { sort -n | awk '{a[NR]=$1} END {print a[int((NR+1)/2)]}'; }

field() { grep -Eo "$1" "$OUT/run.log.stdout" | head -1 | tr -dc '0-9'; }

photos=$DATA/photos-$COUNT
if [ ! -d "$photos" ]; then "$DEV" make-bench-data --count "$COUNT" --output "$photos" >&2; fi
size=$(du -sh "$photos" | cut -f1)
cache=$OUT/cache.json
report=$OUT/report

echo "## Benchmark results"
echo
echo "- Machine: $(sysctl -n hw.model), $(sysctl -n machdep.cpu.brand_string), $(sysctl -n hw.ncpu) cores, $(( $(sysctl -n hw.memsize) / 1073741824 )) GB RAM"
echo "- OS: macOS $(sw_vers -productVersion); $(swift --version 2>&1 | head -1)"
echo "- Dataset: $COUNT synthetic JPEGs (2400 px long side, $size total; 80% unique, 10% exact copies, 10% resized near-duplicates), generated by \`photosweep-dev make-bench-data\`"
echo "- Method: release build, median of $RUNS runs, OS file cache warm (not purged). Wall time is the scan's own timer (discovery through grouping, excluding report thumbnails); memory is peak RSS of the whole process from \`/usr/bin/time -l\`."
echo

echo "### Cache effectiveness and incremental work (8 workers)"
echo
echo "| Scenario | Time (s) | Files decoded | Files hashed | Cache hits |"
echo "|---|---:|---:|---:|---:|"
cold=(); warm=(); inc=()
for i in $(seq "$RUNS"); do
  rm -f "$cache"
  cold+=("$(run "$photos" -o "$report" --cache "$cache" --workers 8 | cut -d' ' -f1)")
  cd_fp=$(field 'fingerprints computed: [0-9]+'); cd_h=$(field 'hashes computed: [0-9]+'); cd_hit=$(field 'Cache hits: [0-9]+')
  warm+=("$(run "$photos" -o "$report" --cache "$cache" --workers 8 | cut -d' ' -f1)")
  w_fp=$(field 'fingerprints computed: [0-9]+'); w_h=$(field 'hashes computed: [0-9]+'); w_hit=$(field 'Cache hits: [0-9]+')
done
echo "| Cold scan (empty cache) | $(printf '%s\n' "${cold[@]}" | median) | $cd_fp | $cd_h | $cd_hit |"
echo "| Repeat scan, nothing changed | $(printf '%s\n' "${warm[@]}" | median) | $w_fp | $w_h | $w_hit |"
# Incremental: modify 1% of files (fresh copy each run so every run modifies the same number).
for i in $(seq "$RUNS"); do
  rm -f "$cache"; run "$photos" -o "$report" --cache "$cache" --workers 8 >/dev/null
  "$DEV" touch "$photos" --every 100 >/dev/null
  inc+=("$(run "$photos" -o "$report" --cache "$cache" --workers 8 | cut -d' ' -f1)")
  i_fp=$(field 'fingerprints computed: [0-9]+'); i_h=$(field 'hashes computed: [0-9]+'); i_hit=$(field 'Cache hits: [0-9]+')
done
echo "| Repeat scan after modifying 1% of files | $(printf '%s\n' "${inc[@]}" | median) | $i_fp | $i_h | $i_hit |"
echo

echo "### Worker count (cold scan, cache disabled)"
echo
echo "| Workers | Time (s) | Speed-up vs 1 | Peak RSS (MB) |"
echo "|---:|---:|---:|---:|"
base=""
for w in 1 2 4 8 10; do
  ts=(); rss=()
  for i in $(seq "$RUNS"); do
    r=$(run "$photos" -o "$report" --no-cache --workers "$w")
    ts+=("${r% *}"); rss+=("${r#* }")
  done
  t=$(printf '%s\n' "${ts[@]}" | median); m=$(printf '%s\n' "${rss[@]}" | median)
  [ -z "$base" ] && base=$t
  speedup=$(awk -v b="$base" -v t="$t" 'BEGIN { printf "%.2fx", b / t }' </dev/null)
  echo "| $w | $t | $speedup | $(( m / 1048576 )) |"
done
echo

echo "### Peak memory vs collection size (cold scan, 8 workers, cache disabled)"
echo
echo "| Files | Dataset size | Time (s) | Peak RSS (MB) |"
echo "|---:|---:|---:|---:|"
for n in ${MEMORY_COUNTS[@]}; do
  dir=$DATA/photos-$n
  if [ ! -d "$dir" ]; then "$DEV" make-bench-data --count "$n" --output "$dir" >&2; fi
  r=$(run "$dir" -o "$OUT/report-$n" --no-cache --workers 8)
  echo "| $n | $(du -sh "$dir" | cut -f1) | ${r% *} | $(( ${r#* } / 1048576 )) |"
done
